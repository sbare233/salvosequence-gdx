    private static Ship l(String name, String slug, String role, int tier, String kit, String perkSpec,
                          int hp, int shield, int plate, int flak, int volley,
                          int energy, int draw, String lore) {
        ShipRole r = switch (role) {
            case "sub" -> ShipRole.SECONDARY_GUN;
            case "armor" -> ShipRole.ARMOR;
            case "drive" -> ShipRole.DRIVE;
            case "flag" -> ShipRole.TACTICS;
            default -> ShipRole.MAIN_GUN;
        };
        List<Perk> perks = perkSpec == null ? List.of() : List.of(parse(perkSpec));
        String zh = role.equals("flag") ? name + " 归航舰" : name;
        String id = "leg." + slug;
        String en = "LEGEND " + slug.toUpperCase().replace('.', '-');
        return new Ship(id, zh, en, r, 2, 2,
                hp, shield, plate, flak, volley, energy, draw,
                List.of(kit.split("\\|")), perks, tier, lore);
    }

    private static Perk parse(String spec) {
        String[] p = spec.split("[|]");
        return new Perk(Perk.Kind.valueOf(p[0]), Integer.parseInt(p[2]), Perk.Range.valueOf(p[1]));
    }

